# Напиши программу, которая:
# 1. Запрашивает у пользователя предложение через input().
# 2. Убирает пробелы по краям.
# 3. Переводит текст в нижний регистр.
# 4. Разделяет предложение на слова.
# 5. Выводит:
#    - исходное предложение после очистки;
#    - количество слов;
#    - первое слово;
#    - последнее слово;
#    - есть ли в предложении слово python.


word1 = input("Введите предложение: ").strip().lower()
words = word1.split()
print(f"Исходное предложение: {word1}")
print(f"Количество слов: {len(words)}")
print(f"Первое слово: {words[0]}")
print(f"Последнее слово: {words[-1]}")
print(f"Есть ли в предложении слово 'python': {'python' in words}")